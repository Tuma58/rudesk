#!/usr/bin/env bash
# shellcheck shell=bash

print_port_forward_table() {
  local target="${1:-<LAN-IP>}"
  cat <<EOF

Проброс портов (Port Forwarding) на роутере
===========================================
Направьте внешние порты WAN → внутренний адрес сервера ${target}

  Внешний порт          Протокол    Куда на сервере
  --------------------  --------    -------------------------
  21115                 TCP         ${target}:21115
  21116                 TCP         ${target}:21116
  21116                 UDP         ${target}:21116   ← часто забывают
  21117                 TCP         ${target}:21117
  21118                 TCP         ${target}:21118   (web-клиент, опционально)
  21119                 TCP         ${target}:21119   (web-клиент, опционально)

Минимум для обычного ПК-клиента RustDesk:
  TCP 21115, 21116, 21117  +  UDP 21116  →  ${target}

В клиентах указывайте публичный адрес/домен (не LAN IP): ID server = внешний хост.
EOF
}

install_binaries() {
  local src="${RUDESK_ROOT}/vendor/rustdesk-server/${RUDESK_ARCH}"

  log "Установка бинарников в ${RUDESK_BIN_DIR}"
  mkdir -p "${RUDESK_BIN_DIR}" "${RUDESK_DATA_DIR}" "${RUDESK_LOG_DIR}" "${RUDESK_OPT_DIR}"
  install -m 0755 "${src}/hbbs" "${RUDESK_BIN_DIR}/hbbs"
  install -m 0755 "${src}/hbbr" "${RUDESK_BIN_DIR}/hbbr"

  # Конфиг окружения для unit-файлов и документации
  {
    echo "# Generated by rudesk installer"
    echo "RUDESK_HOST=${RUDESK_HOST}"
    echo "RUDESK_BEHIND_NAT=${RUDESK_BEHIND_NAT:-0}"
    echo "RUDESK_LAN_IP=${RUDESK_LAN_IP:-}"
    if [[ "${RUDESK_ALWAYS_RELAY:-0}" == "1" ]]; then
      echo "ALWAYS_USE_RELAY=Y"
    else
      echo "ALWAYS_USE_RELAY=N"
    fi
  } > "${RUDESK_OPT_DIR}/rudesk.env"
  chmod 0644 "${RUDESK_OPT_DIR}/rudesk.env"

  # Копия метаданных vendor для справки
  cp -f "${RUDESK_ROOT}/vendor/rustdesk-server/VERSION" "${RUDESK_OPT_DIR}/VERSION"
  cp -f "${RUDESK_ROOT}/vendor/rustdesk-server/SOURCE.txt" "${RUDESK_OPT_DIR}/SOURCE.txt" 2>/dev/null || true
}

install_systemd_units() {
  log "Установка systemd unit-файлов"
  install -m 0644 "${RUDESK_ROOT}/systemd/rudesk-hbbs.service" /etc/systemd/system/rudesk-hbbs.service
  install -m 0644 "${RUDESK_ROOT}/systemd/rudesk-hbbr.service" /etc/systemd/system/rudesk-hbbr.service

  # Храним копии скриптов обновления/удаления
  install -m 0755 "${RUDESK_ROOT}/uninstall.sh" "${RUDESK_OPT_DIR}/uninstall.sh"
  install -m 0755 "${RUDESK_ROOT}/update.sh" "${RUDESK_OPT_DIR}/update.sh"
  mkdir -p "${RUDESK_OPT_DIR}/lib" "${RUDESK_OPT_DIR}/systemd" "${RUDESK_OPT_DIR}/vendor/rustdesk-server"
  cp -a "${RUDESK_ROOT}/lib/." "${RUDESK_OPT_DIR}/lib/"
  cp -a "${RUDESK_ROOT}/systemd/." "${RUDESK_OPT_DIR}/systemd/"
  # vendor нужен для update/verify на месте
  cp -a "${RUDESK_ROOT}/vendor/rustdesk-server/." "${RUDESK_OPT_DIR}/vendor/rustdesk-server/"

  systemctl daemon-reload
  systemctl enable rudesk-hbbr.service rudesk-hbbs.service
  systemctl restart rudesk-hbbr.service
  systemctl restart rudesk-hbbs.service
  ok "Сервисы rudesk-hbbs и rudesk-hbbr запущены"
}

wait_for_key() {
  local keyfile="${RUDESK_DATA_DIR}/id_ed25519.pub"
  local i
  log "Ожидание генерации ключа..."
  for i in $(seq 1 30); do
    if [[ -f "${keyfile}" ]]; then
      RUDESK_PUBKEY="$(tr -d '\n' < "${keyfile}")"
      [[ -n "${RUDESK_PUBKEY}" ]] && return 0
    fi
    sleep 1
  done
  die "Ключ ${keyfile} не появился. Проверьте: journalctl -u rudesk-hbbs -e"
}

write_ports_doc() {
  local portsfile="${RUDESK_OPT_DIR}/PORTS.txt"
  if [[ "${RUDESK_BEHIND_NAT:-0}" == "1" ]]; then
    local target="${RUDESK_LAN_IP:-<LAN-IP>}"
    cat > "${portsfile}" <<EOF
rudesk — проброс портов за NAT
==============================

Публичный адрес для клиентов : ${RUDESK_HOST}
Локальный IP сервера (LAN)   : ${target}

На роутере создайте Port Forwarding / Virtual Server:

  WAN :21115/TCP  →  ${target}:21115/TCP
  WAN :21116/TCP  →  ${target}:21116/TCP
  WAN :21116/UDP  →  ${target}:21116/UDP
  WAN :21117/TCP  →  ${target}:21117/TCP
  WAN :21118/TCP  →  ${target}:21118/TCP   (опционально, web-клиент)
  WAN :21119/TCP  →  ${target}:21119/TCP   (опционально, web-клиент)

Минимум: TCP 21115 + TCP/UDP 21116 + TCP 21117.

В клиентах указывайте ${RUDESK_HOST}, а не LAN IP ${target}.
Если белый IP динамический — используйте DDNS-домен.
EOF
  else
    cat > "${portsfile}" <<EOF
rudesk — порты на публичном VPS
===============================

Адрес для клиентов : ${RUDESK_HOST}

В панели хостинга (Security Group / Firewall) откройте входящие:

  TCP 21115-21119
  UDP 21116

Минимум: TCP 21115-21117 и UDP 21116.
EOF
  fi
  chmod 0644 "${portsfile}"
}

write_connection_info() {
  local outfile="${RUDESK_OPT_DIR}/CONNECTION.txt"
  local net_hint
  if [[ "${RUDESK_BEHIND_NAT:-0}" == "1" ]]; then
    net_hint="1. На роутере пробросьте порты на ${RUDESK_LAN_IP} (см. ${RUDESK_OPT_DIR}/PORTS.txt):
   TCP 21115, 21116, 21117 (+ UDP 21116 обязательно).
   Опционально TCP 21118-21119 для web-клиента."
  else
    net_hint="1. В панели хостинга откройте порты (см. ${RUDESK_OPT_DIR}/PORTS.txt):
   TCP 21115-21119 и UDP 21116 (минимум: TCP 21115-21117 и UDP 21116)."
  fi

  write_ports_doc

  cat > "${outfile}" <<EOF
rudesk — параметры подключения клиентов RustDesk
================================================

Режим            : $([[ "${RUDESK_BEHIND_NAT:-0}" == "1" ]] && echo "за NAT" || echo "публичный VPS")
ID / Relay server: ${RUDESK_HOST}
Key              : ${RUDESK_PUBKEY}
$([[ "${RUDESK_BEHIND_NAT:-0}" == "1" ]] && echo "LAN IP сервера  : ${RUDESK_LAN_IP}")

Что сделать дальше
------------------
${net_hint}

2. На каждом ПК установите клиент RustDesk:
   https://github.com/rustdesk/rustdesk/releases

3. В клиенте: Settings → Network → Unlock network settings, затем:
   ID server     = ${RUDESK_HOST}
   Relay server  = ${RUDESK_HOST}   (или оставьте пустым)
   API server    = (пусто)
   Key           = ${RUDESK_PUBKEY}

4. Сохраните настройки и перезапустите клиент RustDesk.

Проверка на сервере:
  systemctl status rudesk-hbbs rudesk-hbbr --no-pager
  journalctl -u rudesk-hbbs -u rudesk-hbbr -e --no-pager
  cat ${RUDESK_OPT_DIR}/PORTS.txt

Данные/ключи: ${RUDESK_DATA_DIR}
Бинарники:    ${RUDESK_BIN_DIR}
Версия OSS:   $(tr -d '\n' < "${RUDESK_OPT_DIR}/VERSION")
EOF
  chmod 0644 "${outfile}"

  echo
  printf '%s' "${C_BOLD}${C_GREEN}"
  echo "Установка завершена."
  printf '%s\n' "${C_RESET}"
  cat "${outfile}"
  echo
  if [[ "${RUDESK_BEHIND_NAT:-0}" == "1" ]]; then
    print_port_forward_table "${RUDESK_LAN_IP}"
    echo
  fi
  ok "Параметры сохранены в ${outfile}"
  ok "Список портов: ${RUDESK_OPT_DIR}/PORTS.txt"
}
